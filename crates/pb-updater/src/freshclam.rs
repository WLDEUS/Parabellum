//! Official ClamAV signatures via `freshclam`, into `clamav/db/` with a generated `freshclam.conf`.
//!
//! Option names checked against `etc/freshclam.conf.sample` of Cisco-Talos/clamav (main branch,
//! fetched 2026-10-25). Exit codes from `libfreshclam/libfreshclam.h` (`FC_SUCCESS = 0`, `FC_UPTODATE = 1`,
//! `FC_EFORBIDDEN = 17`, `FC_ERETRYLATER = 18`). Rate-limit wording from `libfreshclam/libfreshclam.c`
//! ("FreshClam received error code 429/403 …", "You are on cool-down until after: …"); freshclam itself
//! persists the cool-down in `freshclam.dat`, so we simply report it and never retry in a loop.

use crate::process::{run, RunOpts};
use crate::UpdateError;
use pb_core::paths::Paths;
use std::path::{Path, PathBuf};

/// Where `freshclam` is looked for, in order: official `.pkg` (installs to `/usr/local/clamav`),
/// Homebrew (Apple Silicon), legacy `/usr/local/bin`.
pub const FRESHCLAM_CANDIDATES: [&str; 3] = [
    "/usr/local/clamav/bin/freshclam",
    "/opt/homebrew/bin/freshclam",
    "/usr/local/bin/freshclam",
];

const FRESHCLAM_TIMEOUT_SECS: u64 = 30 * 60;
const FC_UPTODATE: i32 = 1;
const FC_EFORBIDDEN: i32 = 17;
const FC_ERETRYLATER: i32 = 18;

/// Locate the freshclam binary.
pub fn find_freshclam() -> Option<PathBuf> {
    FRESHCLAM_CANDIDATES
        .iter()
        .map(PathBuf::from)
        .find(|p| p.is_file())
}

/// First installed freshclam that root may execute (see [`crate::trust`]). freshclam writes the
/// signatures root's scans load, so an untrusted (user-replaceable, e.g. Homebrew) copy is never run —
/// not even as its owner.
pub fn find_trusted_freshclam() -> Result<PathBuf, UpdateError> {
    let mut refused = Vec::new();
    for p in FRESHCLAM_CANDIDATES
        .iter()
        .map(PathBuf::from)
        .filter(|p| p.is_file())
    {
        match crate::process::trusted_for_root(&p) {
            Ok(()) => return Ok(p),
            Err(why) => refused.push(format!("{} ({why})", p.display())),
        }
    }
    if refused.is_empty() {
        Err(UpdateError::NotFound(
            "freshclam (ClamAV non installé)".into(),
        ))
    } else {
        Err(UpdateError::Untrusted(format!(
            "{} — installer le paquet officiel ClamAV (composant « clamav »)",
            refused.join(", ")
        )))
    }
}

/// Render `freshclam.conf` for our database directory.
pub(crate) fn render_freshclam_conf(db_dir: &Path) -> String {
    // Values may contain spaces ("Application Support"); freshclam's parser accepts double-quoted values.
    format!(
        "# Generated by Parabellum before every run — do not edit.\n\
         DatabaseDirectory \"{}\"\n\
         DatabaseOwner root\n\
         DatabaseMirror database.clamav.net\n\
         Checks 1\n\
         MaxAttempts 3\n\
         ConnectTimeout 30\n\
         ReceiveTimeout 300\n\
         TestDatabases yes\n\
         Bytecode yes\n\
         Foreground yes\n\
         LogTime yes\n",
        db_dir.display()
    )
}

/// Outcome classification of a freshclam run.
#[derive(Debug, PartialEq, Eq)]
pub(crate) enum FreshclamResult {
    Updated(String),
    UpToDate(String),
    CoolDown(String),
    Failed(String),
}

pub(crate) fn classify(code: Option<i32>, output: &str) -> FreshclamResult {
    let cool = output.lines().find(|l| {
        let l = l.to_ascii_lowercase();
        l.contains("cool-down") || l.contains("error code 429") || l.contains("error code 403")
    });
    if let Some(line) = cool {
        // Prefer the "until after" line if present.
        let until = output
            .lines()
            .find(|l| l.contains("cool-down until"))
            .unwrap_or(line);
        return FreshclamResult::CoolDown(until.trim().to_string());
    }
    if matches!(code, Some(FC_EFORBIDDEN) | Some(FC_ERETRYLATER)) {
        return FreshclamResult::CoolDown(last_line(output));
    }
    let summary: Vec<String> = output
        .lines()
        .map(str::trim)
        .filter(|l| {
            l.contains("up-to-date")
                || l.contains("updated (version")
                || l.contains("Database updated")
        })
        .map(|l| {
            l.trim_start_matches(|c: char| c != ':' && !c.is_alphabetic())
                .to_string()
        })
        .take(6)
        .collect();
    let summary = if summary.is_empty() {
        last_line(output)
    } else {
        summary.join(" ; ")
    };
    match code {
        Some(0) if output.contains("updated (version") || output.contains("Database updated") => {
            FreshclamResult::Updated(summary)
        }
        Some(0) | Some(FC_UPTODATE) => FreshclamResult::UpToDate(summary),
        _ => FreshclamResult::Failed(format!("code {code:?} : {}", last_line(output))),
    }
}

fn last_line(s: &str) -> String {
    s.lines()
        .map(str::trim)
        .rfind(|l| !l.is_empty())
        .unwrap_or("")
        .chars()
        .take(300)
        .collect()
}

/// Run freshclam once (no daemon mode). Returns a one-line summary on success ("up to date" included).
/// A CDN cool-down / rate limit is reported as [`UpdateError::CoolDown`] — callers must not retry
/// before the next scheduled run.
pub async fn run_freshclam(paths: &Paths) -> Result<String, UpdateError> {
    let bin = find_trusted_freshclam()?;
    let db_dir = paths.clamav_db_dir();
    std::fs::create_dir_all(&db_dir)?;
    let conf = paths.clamav_dir().join("freshclam.conf");
    crate::fsutil::atomic_write(&conf, render_freshclam_conf(&db_dir).as_bytes())?;
    let conf_arg = format!("--config-file={}", conf.display());
    let out = run(
        &bin,
        [conf_arg.as_str(), "--stdout"],
        RunOpts::timeout(FRESHCLAM_TIMEOUT_SECS),
    )
    .await?;
    match classify(out.code, &out.combined()) {
        FreshclamResult::Updated(s) => {
            tracing::info!(summary = %s, "freshclam: signatures updated");
            Ok(format!("ClamAV : signatures mises à jour ({s})"))
        }
        FreshclamResult::UpToDate(s) => Ok(format!("ClamAV : signatures à jour ({s})")),
        FreshclamResult::CoolDown(s) => {
            tracing::warn!(detail = %s, "freshclam: CDN cool-down, will retry at the next scheduled run");
            Err(UpdateError::CoolDown(s))
        }
        FreshclamResult::Failed(s) => Err(UpdateError::Command(format!("freshclam {s}"))),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn conf_quotes_paths() {
        let c = render_freshclam_conf(Path::new(
            "/Library/Application Support/Parabellum/clamav/db",
        ));
        assert!(
            c.contains("DatabaseDirectory \"/Library/Application Support/Parabellum/clamav/db\"\n")
        );
        assert!(c.contains("DatabaseMirror database.clamav.net\n"));
        assert!(!c.lines().any(|l| l.starts_with("Example")));
        assert!(!c.contains("NotifyClamd"));
    }

    #[test]
    fn classifies_outputs() {
        let up = "ClamAV update process started at Sat Oct 25 03:00:00 2026\n\
                  daily.cld database is up-to-date (version: 27800, sigs: 2075478, f-level: 90, builder: raynman)\n\
                  main.cvd database is up-to-date (version: 62, sigs: 6647427, f-level: 90, builder: sigmgr)\n";
        assert!(matches!(
            classify(Some(0), up),
            FreshclamResult::UpToDate(_)
        ));
        assert!(matches!(
            classify(Some(1), up),
            FreshclamResult::UpToDate(_)
        ));
        let upd =
            "daily.cld updated (version: 27801, sigs: 2075500, f-level: 90, builder: raynman)\n";
        assert!(matches!(
            classify(Some(0), upd),
            FreshclamResult::Updated(_)
        ));
        let cool = "WARNING: FreshClam received error code 429 from the ClamAV Content Delivery Network (CDN).\n\
                    WARNING: You are on cool-down until after: 2026-10-26 03:00:00\n";
        match classify(Some(18), cool) {
            FreshclamResult::CoolDown(s) => assert!(s.contains("until after")),
            o => panic!("{o:?}"),
        }
        assert!(matches!(
            classify(Some(17), "error"),
            FreshclamResult::CoolDown(_)
        ));
        assert!(matches!(
            classify(Some(5), "ERROR: Can't connect"),
            FreshclamResult::Failed(_)
        ));
    }
}
